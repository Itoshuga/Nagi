/** Export trusted Lucide vectors before Next starts; never import its full registry in Next. */
import { createRequire } from 'node:module';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL, URL } from 'node:url';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(new URL('../apps/web/package.json', import.meta.url));
const packageDir = dirname(require.resolve('lucide-react/package.json'));
const { version } = JSON.parse(await readFile(join(packageDir, 'package.json'), 'utf8'));
const { default: imports } = await import(
  pathToFileURL(require.resolve('lucide-react/dynamicIconImports.mjs')).href
);
const names = Object.keys(imports).sort();
const catalog = `${JSON.stringify(names, null, 2)}\n`;
const fingerprint = createHash('sha256')
  .update(version + catalog + 'svg-export-v2')
  .digest('hex');
const assetVersion = `${version}-${fingerprint.slice(0, 10)}`;
const versionModule = `// Generated by scripts/generate-lucide-icons.mjs.\nexport const lucideAssetVersion = '${assetVersion}';\n`;
const catalogPath = join(root, 'apps/web/src/features/icons/names.generated.json');
const versionPath = join(root, 'apps/web/src/features/icons/version.generated.ts');
const directory = join(root, 'apps/web/public/icons/lucide', assetVersion);
const read = async (path) => readFile(path, 'utf8').catch(() => '');
const metadataCurrent =
  (await read(catalogPath)) === catalog && (await read(versionPath)) === versionModule;

if (process.argv.includes('--check')) {
  if (!metadataCurrent) throw new Error('Catalogue Lucide obsolète : lancez pnpm icons:generate.');
  console.log(`Catalogue Lucide conforme (${names.length} icônes).`);
} else {
  if (!metadataCurrent) {
    await writeFile(catalogPath, catalog);
    await writeFile(versionPath, versionModule);
  }
  const files = await readdir(directory).catch(() => []);
  if (
    (await read(join(directory, '.fingerprint'))) !== fingerprint ||
    files.filter((name) => name.endsWith('.svg')).length !== names.length
  ) {
    await mkdir(directory, { recursive: true });
    const license = await readFile(join(packageDir, 'LICENSE'), 'utf8');
    const escape = (value) =>
      String(value)
        .replaceAll('&', '&amp;')
        .replaceAll('"', '&quot;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;');
    // Limit startup IO; this executes once per library version, outside the bundler.
    for (let offset = 0; offset < names.length; offset += 64) {
      await Promise.all(
        names.slice(offset, offset + 64).map(async (name) => {
          const { __iconNode: nodes } = await imports[name]();
          const content = nodes
            .map(
              ([tag, attrs]) =>
                `<${tag} ${Object.entries(attrs)
                  .filter(([key]) => key !== 'key')
                  .map(
                    ([key, value]) =>
                      `${key.replace(/[A-Z]/g, (char) => '-' + char.toLowerCase())}="${escape(value)}"`,
                  )
                  .join(' ')}/>`,
            )
            .join('');
          const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><metadata>${escape(license.trim())}</metadata>${content}</svg>\n`;
          await writeFile(join(directory, `${name}.svg`), svg);
        }),
      );
    }
    await writeFile(join(directory, '.fingerprint'), fingerprint);
    console.log(`${names.length} SVG Lucide générés (v${version}).`);
  }
}
